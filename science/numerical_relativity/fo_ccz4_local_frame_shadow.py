"""Deterministic local orthonormal-frame contract for the FO-CCZ4 shadow.

The variable-coefficient boundary audit validates local speeds, but a future
local characteristic basis also needs a metric-aware frame.  This module
constructs that frame from a covariant spatial metric and a boundary normal
*covector*.  Rows of the returned matrix are contravariant frame vectors
``e_a^i`` and satisfy

``E @ gamma @ E.T = I``

with row zero equal to the outward unit normal vector.  The two tangent rows
are generated by deterministic metric Gram--Schmidt and a sign is chosen so
that the frame has positive coordinate determinant.

This is a geometry/coordinate-frame contract only.  It is not a transformed
58-variable principal symbol, a variable-coefficient symmetrizer, a nonlinear
CPBC, a physical boundary condition, or a runtime writeback path.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import math

import numpy as np

from .nr3d import BSSNState3D


@dataclass(frozen=True)
class FOCCZ4LocalFrameAudit3D:
    """Deterministic metric-frame audit over selected oriented outer faces."""

    axes: tuple[int, ...]
    face_count: int
    boundary_cell_count: int
    max_metric_orthonormality_residual: float
    max_normal_covector_residual: float
    max_euclidean_orthogonality_defect: float
    min_frame_determinant: float
    max_frame_determinant: float
    max_frame_condition_number: float
    frame_sha256: str
    deterministic: bool
    local_orthonormal_frame_validated: bool
    variable_coefficient_principal_proxy_validated: bool
    variable_coefficient_boundary_validated: bool
    nonlinear_cpbc_validated: bool
    physical_boundary_validated: bool
    runtime_writeback: bool
    method: str = "fo-ccz4-local-orthonormal-frame-shadow-v1"

    def __post_init__(self) -> None:
        if not self.axes or any(axis not in (0, 1, 2) for axis in self.axes):
            raise ValueError("axes must contain one or more Cartesian axes")
        if len(set(self.axes)) != len(self.axes):
            raise ValueError("axes must not repeat")
        if self.face_count <= 0 or self.boundary_cell_count <= 0:
            raise ValueError("local frame audit must contain at least one face")
        if not self.frame_sha256 or len(self.frame_sha256) != 64:
            raise ValueError("frame_sha256 must be a SHA-256 digest")


def local_orthonormal_frame_from_metric_3d(
    metric: np.ndarray,
    normal_covector: np.ndarray,
    *,
    tolerance: float = 1.0e-12,
) -> np.ndarray:
    """Construct a positive-orientation metric-orthonormal frame.

    Parameters
    ----------
    metric:
        A finite symmetric positive-definite covariant spatial metric.
    normal_covector:
        A finite non-zero covector defining the oriented boundary normal.
    tolerance:
        Absolute lower bound for the metric spectrum and Gram--Schmidt norms.

    Returns
    -------
    numpy.ndarray
        A real ``(3, 3)`` array whose rows are contravariant frame vectors.
    """

    tolerance = float(tolerance)
    if not math.isfinite(tolerance) or tolerance < 0.0:
        raise ValueError("tolerance must be finite and non-negative")
    matrix = np.asarray(metric, dtype=np.float64)
    covector = np.asarray(normal_covector, dtype=np.float64)
    if matrix.shape != (3, 3) or not np.all(np.isfinite(matrix)):
        raise ValueError("metric must be a finite 3-by-3 matrix")
    if not np.allclose(matrix, matrix.T, rtol=0.0, atol=1.0e-13):
        raise ValueError("metric must be symmetric")
    matrix = 0.5 * (matrix + matrix.T)
    spectrum = np.linalg.eigvalsh(matrix)
    if float(spectrum[0]) <= tolerance:
        raise ValueError("metric must be positive definite")
    if covector.shape != (3,) or not np.all(np.isfinite(covector)):
        raise ValueError("normal_covector must contain three finite components")
    try:
        inverse = np.linalg.inv(matrix)
    except np.linalg.LinAlgError as exc:  # pragma: no cover - SPD guard
        raise ValueError("metric must be invertible") from exc
    normal_norm_squared = float(covector @ inverse @ covector)
    if not math.isfinite(normal_norm_squared) or normal_norm_squared <= tolerance:
        raise ValueError("normal_covector must have positive metric norm")
    unit_normal = inverse @ covector / math.sqrt(normal_norm_squared)

    rows: list[np.ndarray] = [unit_normal]
    for seed_axis in range(3):
        seed = np.zeros(3, dtype=np.float64)
        seed[seed_axis] = 1.0
        tangent = seed.copy()
        for row in rows:
            tangent -= row * float(row @ matrix @ tangent)
        norm_squared = float(tangent @ matrix @ tangent)
        if not math.isfinite(norm_squared) or norm_squared <= tolerance:
            continue
        rows.append(tangent / math.sqrt(norm_squared))
        if len(rows) == 3:
            break
    if len(rows) != 3:  # pragma: no cover - a 3-D SPD metric has rank three
        raise ValueError("metric Gram-Schmidt could not construct two tangents")
    frame = np.asarray(rows, dtype=np.float64)
    determinant = float(np.linalg.det(frame))
    if not math.isfinite(determinant) or abs(determinant) <= tolerance:
        raise ValueError("local frame must have a finite non-zero determinant")
    if determinant < 0.0:
        frame[2] *= -1.0
    return frame


def _validate_state_inputs(
    state: BSSNState3D,
    axes: tuple[int, ...],
    tolerance: float,
) -> tuple[int, ...]:
    if state.grid.boundary != "sommerfeld":
        raise ValueError(
            "local frame audit requires Grid3D(boundary='sommerfeld')"
        )
    if not np.all(state.valid_mask):
        raise ValueError("local frame audit requires a fully valid state")
    if not axes or any(axis not in (0, 1, 2) for axis in axes):
        raise ValueError("axes must contain one or more values from 0, 1, or 2")
    if len(set(axes)) != len(axes):
        raise ValueError("axes must not repeat")
    if not math.isfinite(tolerance) or tolerance < 0.0:
        raise ValueError("tolerance must be finite and non-negative")
    return tuple(int(axis) for axis in axes)


def _face_indices(shape: tuple[int, int, int], axis: int, side: int):
    fixed = 0 if side < 0 else shape[axis] - 1
    for index in np.ndindex(shape):
        if index[axis] == fixed:
            yield index


def audit_fo_ccz4_local_frame_3d(
    state: BSSNState3D,
    *,
    axes: tuple[int, ...] = (0, 1, 2),
    tolerance: float = 1.0e-12,
    residual_tolerance: float = 1.0e-10,
) -> FOCCZ4LocalFrameAudit3D:
    """Audit metric-orthonormal frames over selected outer faces."""

    tolerance = float(tolerance)
    residual_tolerance = float(residual_tolerance)
    axes = _validate_state_inputs(state, axes, tolerance)
    if not math.isfinite(residual_tolerance) or residual_tolerance < 0.0:
        raise ValueError("residual_tolerance must be finite and non-negative")
    metric_residuals: list[float] = []
    normal_residuals: list[float] = []
    euclidean_defects: list[float] = []
    determinants: list[float] = []
    condition_numbers: list[float] = []
    boundary_cells: set[tuple[int, int, int]] = set()
    digest = hashlib.sha256()
    face_count = 0
    identity = np.eye(3, dtype=np.float64)
    shape = state.grid.shape
    for axis in axes:
        for side in (-1, 1):
            normal_covector = np.zeros(3, dtype=np.float64)
            normal_covector[axis] = float(side)
            for index in _face_indices(shape, axis, side):
                boundary_cells.add(index)
                chi = float(state.chi[index])
                if not math.isfinite(chi) or chi <= 0.0:
                    raise ValueError("boundary chi must be finite and positive")
                conformal_metric = np.asarray(state.h[index], dtype=np.float64)
                if not np.allclose(
                    conformal_metric,
                    conformal_metric.T,
                    rtol=0.0,
                    atol=1.0e-13,
                ):
                    raise ValueError("boundary conformal metric must be symmetric")
                metric = 0.5 * (conformal_metric + conformal_metric.T) / chi
                frame = local_orthonormal_frame_from_metric_3d(
                    metric,
                    normal_covector,
                    tolerance=tolerance,
                )
                metric_residual = float(np.max(np.abs(frame @ metric @ frame.T - identity)))
                inverse = np.linalg.inv(metric)
                normal_target = normal_covector / math.sqrt(
                    float(normal_covector @ inverse @ normal_covector)
                )
                normal_residual = float(np.max(np.abs(frame[0] @ metric - normal_target)))
                euclidean_defect = float(np.max(np.abs(frame @ frame.T - identity)))
                determinant = float(np.linalg.det(frame))
                condition_number = float(np.linalg.cond(frame))
                if not all(
                    math.isfinite(value)
                    for value in (
                        metric_residual,
                        normal_residual,
                        euclidean_defect,
                        determinant,
                        condition_number,
                    )
                ):
                    raise ValueError("local frame diagnostics must be finite")
                metric_residuals.append(metric_residual)
                normal_residuals.append(normal_residual)
                euclidean_defects.append(euclidean_defect)
                determinants.append(determinant)
                condition_numbers.append(condition_number)
                digest.update(
                    np.asarray(
                        (
                            *index,
                            axis,
                            side,
                            chi,
                            *metric.reshape(-1),
                            *frame.reshape(-1),
                            metric_residual,
                            normal_residual,
                            determinant,
                            condition_number,
                        ),
                        dtype="<f8",
                    ).tobytes()
                )
                face_count += 1
    if face_count == 0:
        raise ValueError("selected axes produced no boundary faces")
    frame_validated = bool(
        max(metric_residuals) <= residual_tolerance
        and max(normal_residuals) <= residual_tolerance
        and min(determinants) > 0.0
        and np.all(np.isfinite(condition_numbers))
    )
    return FOCCZ4LocalFrameAudit3D(
        axes=axes,
        face_count=face_count,
        boundary_cell_count=len(boundary_cells),
        max_metric_orthonormality_residual=float(max(metric_residuals)),
        max_normal_covector_residual=float(max(normal_residuals)),
        max_euclidean_orthogonality_defect=float(max(euclidean_defects)),
        min_frame_determinant=float(min(determinants)),
        max_frame_determinant=float(max(determinants)),
        max_frame_condition_number=float(max(condition_numbers)),
        frame_sha256=digest.hexdigest(),
        deterministic=True,
        local_orthonormal_frame_validated=frame_validated,
        variable_coefficient_principal_proxy_validated=False,
        variable_coefficient_boundary_validated=False,
        nonlinear_cpbc_validated=False,
        physical_boundary_validated=False,
        runtime_writeback=False,
    )


