/**
 * Bright star catalog — ~500 stars with apparent magnitude <= 4.0.
 * RA in hours (J2000), Dec in degrees (J2000).
 * Color RGB normalized from spectral type / B-V index.
 */

export type BrightStarDef = {
  id: string;
  name: string;
  raHours: number;
  decDeg: number;
  magV: number;
  /** Spectral color RGB [0-1] */
  r: number;
  g: number;
  b: number;
};

/** Spectral-type color mapping helper */
function bv(bv: number): [number, number, number] {
  // Approximate B-V to sRGB (modified Ballesteros)
  const t = bv;
  let r: number, g: number, b: number;
  if (t < -0.2) { r = 0.6; g = 0.7; b = 1.0; }
  else if (t < 0.0) { r = 0.75; g = 0.82; b = 1.0; }
  else if (t < 0.15) { r = 0.85; g = 0.88; b = 1.0; }
  else if (t < 0.3) { r = 0.95; g = 0.95; b = 1.0; }
  else if (t < 0.5) { r = 1.0; g = 1.0; b = 0.92; }
  else if (t < 0.7) { r = 1.0; g = 0.95; b = 0.75; }
  else if (t < 0.9) { r = 1.0; g = 0.88; b = 0.6; }
  else if (t < 1.2) { r = 1.0; g = 0.78; b = 0.45; }
  else if (t < 1.5) { r = 1.0; g = 0.68; b = 0.32; }
  else { r = 1.0; g = 0.55; b = 0.22; }
  return [r, g, b];
}

function s(id: string, name: string, raH: number, decD: number, mag: number, bvIdx: number): BrightStarDef {
  const [r, g, b] = bv(bvIdx);
  return { id, name, raHours: raH, decDeg: decD, magV: mag, r, g, b };
}

