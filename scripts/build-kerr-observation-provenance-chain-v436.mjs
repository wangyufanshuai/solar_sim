import { spawnSync } from "node:child_process";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
const root = process.cwd();
const temp = resolve(root, "dist/temp/v436");
mkdirSync(temp, { recursive: true });
const env = { ...process.env, TEMP: temp, TMP: temp };
const run = (label, command, args) => { const result = spawnSync(command, args, { cwd: root, stdio: "inherit", shell: false, env }); if (result.error) throw result.error; if (result.status !== 0) throw new Error(`${label} failed with ${result.status}`); };
run("v436 Python provenance oracle", "python", ["scripts/run-kerr-observation-provenance-oracle-v436.py"]);
run("v436 TypeScript artifact builder", process.execPath, [resolve(root, "node_modules/tsx/dist/cli.mjs"), "scripts/build-kerr-observation-provenance-v436.ts"]);
