import fs from "node:fs";
import path from "node:path";

// Merge the already verified six-image local delivery with the separately
// reviewed six-image extension receipt. This creates a new generated registry
// without rewriting either historical receipt.
const root = process.cwd();
const readJson = (relative) => JSON.parse(fs.readFileSync(path.join(root, relative), "utf8"));
const first = readJson("docs/release/v607/mainline-a-stage-a3-local-delivery.json");
const extension = readJson("docs/release/v607/mainline-a-stage-a3-extension-delivery.json");
if (first.assets?.length !== 6 || extension.objects?.length !== 6) throw new Error("A3 requires two six-image inputs");

const normalize = (asset) => ({
  objectId: asset.objectId,
  imageId: asset.imageId,
  src: asset.src,
  localPath: asset.localPath,
  sourcePage: asset.sourcePage,
  imageUrl: asset.imageUrl,
  credit: asset.credit,
  license: "CC BY 4.0",
  licenseUrl: asset.licenseUrl,
  rightsPage: asset.rightsPage,
  rightsStatus: "cleared",
  rightsReviewedAt: asset.rightsReviewedAt,
  retrievedAt: asset.retrievedAt,
  bands: asset.bands,
  dimensions: asset.dimensions,
  byteSize: asset.byteSize,
  sha256: asset.sha256,
  rendition: "official-screen-jpeg",
  modifications: asset.modifications,
  nakedEyeRepresentationClaimed: false,
});

const assets = [...first.assets, ...extension.objects].map(normalize);
const ids = new Set();
for (const asset of assets) {
  if (ids.has(asset.objectId) || !/^\/textures\/mainline-a\/[a-z0-9-]+\.jpg$/.test(asset.src)) throw new Error(`A3 duplicate or invalid asset: ${asset.objectId}`);
  ids.add(asset.objectId);
  const bytes = fs.readFileSync(path.join(root, asset.localPath));
  if (bytes.byteLength !== asset.byteSize) throw new Error(`${asset.objectId}: byte size mismatch`);
}

const output = "app/data/mainlineANebulaVisualAssetsV607.all.generated.ts";
const type = `export type MainlineANebulaVisualAssetV607All = {\n  objectId: string; imageId: string; src: string; localPath: string; sourcePage: string; imageUrl: string;\n  credit: string; license: "CC BY 4.0"; licenseUrl: string; rightsPage: string; rightsStatus: "cleared"; rightsReviewedAt: string; retrievedAt: string;\n  bands: readonly string[]; dimensions: { width: number; height: number }; byteSize: number; sha256: string;\n  rendition: "official-screen-jpeg"; modifications: string; nakedEyeRepresentationClaimed: false;\n};\n`;
const source = `// Generated by node scripts/materialize-mainline-a3-all-assets.mjs. Do not edit by hand.\n${type}\nexport const MAINLINE_A3_NEBULA_VISUAL_ASSETS_ALL: readonly MainlineANebulaVisualAssetV607All[] = Object.freeze(${JSON.stringify(assets, null, 2)});\n\nexport const getMainlineANebulaVisualAssetV607All = (objectId: string): MainlineANebulaVisualAssetV607All | undefined =>\n  MAINLINE_A3_NEBULA_VISUAL_ASSETS_ALL.find((asset) => asset.objectId === objectId);\n`;
fs.writeFileSync(path.join(root, output), source);
const creditsPath = "public/textures/mainline-a/CREDITS.md";
const credits = [
  "# Mainline A — official astronomy images",
  "",
  "These twelve local JPEGs are candidate visual previews. Their source pages, CC BY 4.0 license labels, and item credits are recorded below; individual human rights signoff is pending for all twelve. The source license label is not a project copyright approval. ESA/Hubble items also reference the [ESA/Hubble conditions](https://esahubble.org/copyright/); the ESO item references the [ESO public-use policy](https://www.eso.org/public/outreach/copyright/). Keep the full item credit visible beside every preview and keep source links active. The images do not imply ESA/Hubble or ESO endorsement. Logos are not included.",
  "",
  ...assets.map((asset) => `- [${asset.imageId}](${asset.sourcePage}) — ${asset.credit}`),
  "",
].join("\n");
fs.writeFileSync(path.join(root, creditsPath), credits);
console.log(JSON.stringify({ status: "materialized-all-a3-assets", assetCount: assets.length, totalByteSize: assets.reduce((sum, asset) => sum + asset.byteSize, 0), output, creditsPath }, null, 2));
