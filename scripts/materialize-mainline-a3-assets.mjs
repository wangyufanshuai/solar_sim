import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

// Materializes the six reviewed ESA/Hubble screen JPEGs without altering them.
// The historical in-memory receipt is immutable input; the delivery manifest
// records the local files separately. Existing files are verified, not replaced.
const root = process.cwd();
const readJson = (name) => JSON.parse(fs.readFileSync(path.join(root, name), "utf8"));
const sha256 = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");
const reviewPath = "docs/release/v607/mainline-a-stage-a3-rights-review.json";
const review = readJson(reviewPath);
const acquisitionPath = "docs/release/v607/mainline-a-stage-a3-image-acquisition.json";
const acquisition = readJson(acquisitionPath);
const outputPath = "docs/release/v607/mainline-a-stage-a3-local-delivery.json";
const generatedPath = "app/data/mainlineANebulaVisualAssetsV607.generated.ts";
const candidates = readJson("docs/release/v607/mainline-a-stage-a3-candidate-audit.json").candidates;
const textureDir = path.join(root, "public/textures/mainline-a");
fs.mkdirSync(textureDir, { recursive: true });

if (review.status !== "cleared-under-published-license" || review.license !== "CC BY 4.0" || review.candidates.length !== 6) {
  throw new Error("A3 requires six item-specific published-license review decisions");
}

const assets = [];
for (const candidate of candidates) {
  const decision = review.candidates.find((row) => row.objectId === candidate.objectId && row.imageId === candidate.imageId);
  const receipt = acquisition.candidates.find((row) => row.objectId === candidate.objectId && row.imageId === candidate.imageId);
  if (!decision || decision.status !== "cleared" || decision.explicitException !== null || !decision.policyLinkedFromImagePage || decision.sourcePage !== candidate.sourcePage || decision.credit !== candidate.credit || !receipt || receipt.sourcePage !== candidate.sourcePage) {
    throw new Error(`A3 asset lacks a matching item-level clearance: ${candidate.objectId}`);
  }
  const localPath = `public/textures/mainline-a/${candidate.imageId}.jpg`;
  const target = path.join(root, localPath);
  let bytes;
  if (fs.existsSync(target)) {
    bytes = fs.readFileSync(target);
  } else {
    const response = await fetch(receipt.imageUrl, { signal: AbortSignal.timeout(45_000), redirect: "follow" });
    if (!response.ok || !response.headers.get("content-type")?.startsWith("image/jpeg")) {
      throw new Error(`${candidate.imageId}: expected HTTP 200 image/jpeg`);
    }
    bytes = Buffer.from(await response.arrayBuffer());
  }
  if (bytes.byteLength !== receipt.byteSize || sha256(bytes) !== receipt.sha256) {
    throw new Error(`${candidate.imageId}: bytes do not match the reviewed acquisition receipt`);
  }
  if (!fs.existsSync(target)) fs.writeFileSync(target, bytes, { flag: "wx" });
  assets.push({
    objectId: candidate.objectId,
    imageId: candidate.imageId,
    src: `/textures/mainline-a/${candidate.imageId}.jpg`,
    localPath,
    sourcePage: candidate.sourcePage,
    imageUrl: receipt.imageUrl,
    credit: candidate.credit,
    license: review.license,
    licenseUrl: review.licenseUrl,
    rightsPage: review.rightsPage,
    rightsStatus: "cleared",
    rightsReviewedAt: review.reviewedAt,
    retrievedAt: receipt.retrievedAt,
    bands: candidate.bands,
    dimensions: receipt.dimensions,
    byteSize: receipt.byteSize,
    sha256: receipt.sha256,
    rendition: "official-screen-jpeg",
    modifications: "none; official screen JPEG bytes retained",
    nakedEyeRepresentationClaimed: false,
  });
}

const existing = fs.existsSync(path.join(root, outputPath)) ? readJson(outputPath) : undefined;
const deliveredAt = existing?.deliveredAt ?? new Date().toISOString();
const manifest = {
  schema: "mainline-a3-local-delivery-v1",
  status: "six-licensed-local-assets-delivered-ui-integration-pending",
  deliveredAt,
  rightsReview: reviewPath,
  historicalAcquisitionReceipt: acquisitionPath,
  localPayload: { acquired: true, licensed: true, storage: "public/textures/mainline-a" },
  totalByteSize: assets.reduce((sum, asset) => sum + asset.byteSize, 0),
  assets,
};
fs.writeFileSync(path.join(root, outputPath), `${JSON.stringify(manifest, null, 2)}\n`);
const type = `export type MainlineANebulaVisualAssetV607 = {\n  objectId: string; imageId: string; src: string; localPath: string; sourcePage: string; imageUrl: string;\n  credit: string; license: "CC BY 4.0"; licenseUrl: string; rightsPage: string; rightsStatus: "cleared"; rightsReviewedAt: string; retrievedAt: string;\n  bands: readonly string[]; dimensions: { width: number; height: number }; byteSize: number; sha256: string;\n  rendition: "official-screen-jpeg"; modifications: string; nakedEyeRepresentationClaimed: false;\n};\n`;
fs.writeFileSync(path.join(root, generatedPath), `// Generated by node scripts/materialize-mainline-a3-assets.mjs. Do not edit by hand.\n${type}\nexport const MAINLINE_A3_NEBULA_VISUAL_ASSETS: readonly MainlineANebulaVisualAssetV607[] = Object.freeze(${JSON.stringify(assets, null, 2)});\n\nexport const getMainlineANebulaVisualAssetV607 = (objectId: string): MainlineANebulaVisualAssetV607 | undefined =>\n  MAINLINE_A3_NEBULA_VISUAL_ASSETS.find((asset) => asset.objectId === objectId);\n`);
fs.writeFileSync(path.join(textureDir, "CREDITS.md"), `# Mainline A — ESA/Hubble images\n\nThese six official screen JPEGs are reused unchanged under [CC BY 4.0](${review.licenseUrl}) and the [ESA/Hubble conditions](${review.rightsPage}). Show the full item credit visibly beside every use, keep links active, and describe any later significant modifications. The images do not imply ESA/Hubble endorsement. ESA/Hubble logos are not included.\n\n${assets.map((asset) => `- [${asset.imageId}](${asset.sourcePage}): ${asset.credit}`).join("\n")}\n`);
console.log(JSON.stringify({ status: "verified-local-delivery", assetCount: assets.length, totalByteSize: manifest.totalByteSize, manifest: outputPath, runtime: generatedPath }, null, 2));
